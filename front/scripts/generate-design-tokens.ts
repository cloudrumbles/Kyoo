/**
 * Generates the CSS twin of design/tokens.ts. Never edit tokens.generated.css.
 *
 * Run: bun run tokens       Generate the CSS
 *      bun run tokens:check Verify that the committed CSS is current
 */
import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { designTokens } from "../design/tokens";

const root = resolve(import.meta.dir, "..");
const output = resolve(root, "src/design/tokens.generated.css");

const kebab = (name: string) => name.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);
const entries = (value: object, prefix: string): string[] =>
	Object.entries(value).flatMap(([key, child]) => {
		const name = `${prefix}-${kebab(key)}`;
		if (Array.isArray(child)) return [`  --kyoo-${name}: ${child.join(", ")};`];
		if (typeof child === "object" && child !== null) return entries(child, name);
		return [`  --kyoo-${name}: ${String(child)};`];
	});

export function generateTokenCss(tokens: typeof designTokens = designTokens): string {
	const rootVars = [
		...entries(tokens.colors, "color"),
		...entries(tokens.fonts, "font"),
		...entries(tokens.type, "type"),
		...entries(tokens.layout, "layout"),
		...entries(tokens.shape, "shape"),
	].join("\n");

	// Literal values in @theme let Tailwind and Uniwind emit reliable utilities
	// for web AND React Native. Root custom properties provide ordinary CSS
	// with exactly the same source values.
	const themeVars = [
		...Object.entries(tokens.colors).map(([key, color]) =>
			`  --color-kyoo-${kebab(key)}: ${color};`),
		`  --color-accent: ${tokens.colors.accent};`,
		`  --color-background: ${tokens.colors.background};`,
		`  --color-card: ${tokens.colors.surface};`,
		`  --color-popover: ${tokens.colors.surfaceRaised};`,
		`  --color-light: ${tokens.colors.textPrimary};`,
		`  --color-dark: ${tokens.colors.background};`,
		`  --font-sans: ${tokens.fonts.body};`,
		`  --font-headers: ${tokens.fonts.display};`,
	].join("\n");

	return [
		"/* GENERATED by scripts/generate-design-tokens.ts. Edit design/tokens.ts instead. */",
		":root {",
		rootVars,
		"}",
		"",
		"@theme {",
		themeVars,
		"}",
		"",
		"@layer theme {",
		"  :root {",
		"    @variant light {",
		`      --color-background: ${tokens.colors.background};`,
		`      --color-card: ${tokens.colors.surface};`,
		`      --color-popover: ${tokens.colors.surfaceRaised};`,
		"    }",
		"    @variant dark {",
		`      --color-background: ${tokens.colors.background};`,
		`      --color-card: ${tokens.colors.surface};`,
		`      --color-popover: ${tokens.colors.surfaceRaised};`,
		"    }",
		"  }",
		"}",
		"",
	].join("\n");
}

if (import.meta.main) {
	const expected = generateTokenCss();
	if (process.argv.includes("--check")) {
		const actual = await readFile(output, "utf8").catch(() => "");
		if (actual !== expected) {
			console.error("Design tokens are out of sync: run bun run tokens");
			process.exitCode = 1;
		} else {
			console.log("Design tokens are in sync.");
		}
	} else {
		await writeFile(output, expected);
		console.log("Generated src/design/tokens.generated.css");
	}
}
